import { useState } from "react";
import { generateArtifact } from "../services/api";
import SafeMarkdown from "./SafeMarkdown";
import styles from "./ArtifactView.module.css";

export default function ArtifactView({ artifact, onArtifact, onOpenInChat, sessionId = null, provider = null, compact = false }) {
  const [prompt, setPrompt] = useState("");
  const [type, setType] = useState("markdown");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  async function create() {
    setBusy(true); setError("");
    try { const result = await generateArtifact(prompt, type, provider, sessionId); onArtifact?.({type: result.artifact_type, content: result.content, citations: result.citations, abstained: result.abstained}); }
    catch (e) { setError(e.message); }
    finally { setBusy(false); }
  }
  const content = artifact?.content;
  const displayType = artifact?.type ?? type;
  return (
    <div className={styles.view}>
      {!compact && <div className={styles.header}>
        <h1 className={styles.title}>Documents</h1>
        <p className={styles.subtitle}>
          Create a source-grounded Markdown document or isolated HTML/CSS preview.
        </p>
      </div>}

      {!compact && <div><textarea aria-label="Artifact request" value={prompt} onChange={(e)=>setPrompt(e.target.value)} placeholder="Describe an artifact to create from the source library" rows={3} /><select aria-label="Artifact format" value={type} onChange={(e)=>setType(e.target.value)}><option value="markdown">Markdown</option><option value="html">HTML / CSS</option></select><button disabled={busy || prompt.trim().length < 8} onClick={create}>{busy ? "Generating…" : "Generate artifact"}</button>{error && <p role="alert">{error}</p>}</div>}

      {content ? (
        <div className={styles.document} role="region" aria-label="Document content">
          <p>{artifact?.abstained ? "Insufficient evidence" : "Generated source-grounded artifact"} {artifact?.citations?.length > 0 && " · Sources attached"}</p>
          {!compact && !artifact?.abstained && <button type="button" onClick={()=>onOpenInChat?.(artifact)}>Open beside chat</button>}
          {displayType === "html" ? <iframe title="Untrusted HTML artifact preview" sandbox="" referrerPolicy="no-referrer" srcDoc={`<!doctype html><meta charset="utf-8"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; img-src data:; font-src data:; media-src data:; script-src 'none'; connect-src 'none'; frame-src 'none'; object-src 'none'; form-action 'none'; base-uri 'none'"><meta name="viewport" content="width=device-width,initial-scale=1"><style>body{font:16px system-ui;margin:2rem}</style>${content}`} style={{width:"100%",height:"70vh",background:"white",border:0}} /> : <div className={styles.content}><SafeMarkdown source={content} /></div>}
          {artifact?.citations?.map((citation)=><p key={citation.chunk_id}>Source: {citation.source_url ? <a href={citation.source_url} target="_blank" rel="noreferrer">{citation.source_title}</a> : citation.source_title}</p>)}
        </div>
      ) : (
        <div className={styles.empty}>
          <span className={styles.emptyIcon}>📄</span>
          <p>No document open.</p>
          <p className={styles.emptyHint}>
            Documents generated by the assistant will be displayed here.
          </p>
        </div>
      )}
    </div>
  );
}
